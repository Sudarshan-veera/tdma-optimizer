"""Export a schedule as a C header for the ESP32 demo:
   python3 -m tdmaopt.export --nodes 5 --out esp32/tdma_node/schedule.h"""
import argparse

import numpy as np

from . import *


def write_header(path, slots, parent, F, slot_us):
    assert F <= 64, "demo header uses a 64-bit slot mask: frame must be <= 64 slots"
    ids = sorted(slots)
    with open(path, "w") as f:
        f.write("// generated by tdmaopt.export - do not edit\n#pragma once\n#include <stdint.h>\n")
        f.write(f"#define FRAME_SLOTS {F}\n#define SLOT_US {slot_us}\n#define NUM_NODES {max(ids) + 1}\n")
        f.write("// slot mask per node id (bit s set = node transmits in slot s); node 0 = gateway\n")
        f.write("static const uint64_t SLOT_MASK[NUM_NODES] = {\n")
        for v in range(max(ids) + 1):
            m = sum(1 << s for s in slots.get(v, []))
            f.write(f"  0x{m:016x}ULL,  // node {v}\n")
        f.write("};\nstatic const int8_t PARENT[NUM_NODES] = {\n")
        for v in range(max(ids) + 1):
            f.write(f"  {int(parent[v]) if v < len(parent) else -2},\n")
        f.write("};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nodes", type=int, default=5)
    ap.add_argument("--seed", type=int, default=3)
    ap.add_argument("--slot_us", type=int, default=20000)
    ap.add_argument("--out", default="esp32/tdma_node/schedule.h")
    a = ap.parse_args()
    rng = np.random.default_rng(a.seed)
    chan, parent, _ = random_connected(a.nodes, PHY(), rng)
    slots, F = greedy_schedule(conflict_graph(chan, parent), subtree_loads(parent))
    write_header(a.out, slots, parent, F, a.slot_us)
    print(f"wrote {a.out}: {a.nodes} nodes, frame {F} slots")


if __name__ == "__main__":
    main()
