"""Turn results/*.json into docs/RESULTS.md with the real measured numbers."""
import json
from pathlib import Path

R = Path(__file__).resolve().parent.parent
res = R / "results"


def load(n):
    return json.loads((res / f"{n}.json").read_text())


def fmt(x, d=2):
    return "-" if x is None else f"{x:.{d}f}"


def main():
    b, s, e, si, dy, cv = (load(n) for n in ("baselines", "scaling", "exact", "sinr", "dynamic", "coverage"))
    out = ["# Results (auto-generated by `make report` - every number comes from `results/*.json`)\n"]
    st = b["static"]
    out += ["## 1. Baselines\n",
            f"N = {b['N']} radios, {b['seeds']} random topologies, {b['slots_simulated']} simulated slots per run.\n",
            "**Collisions with the same frame length** (random slot choice vs the planner): "
            f"{fmt(sum(r['random_collision_pct'] for r in st)/len(st),1)}% vs "
            f"{fmt(sum(r['greedy_collision_pct'] for r in st)/len(st),1)}% of transmissions.\n",
            "| load (pkt/node/slot) | protocol | gateway throughput (pkt/slot) | delivered | collisions | mean latency (slots) | tx per delivered packet |",
            "|---|---|---|---|---|---|---|"]
    for lam in b["loads"]:
        for proto in ("tdma", "aloha", "csma"):
            r = b["summary"][proto][str(lam)]
            out.append(f"| {lam} | {proto.upper()} | {fmt(r['throughput'],3)} | {fmt(100*r['delivery_ratio'],1)}% | "
                       f"{fmt(100*r['collision_rate'],1)}% | {fmt(r['mean_latency'],1)} | {fmt(r['tx_per_delivery'],2)} |")
    out += ["\n![baselines](../results/baselines.png)\n", "## 2. Scaling\n",
            "| N | frame length | lower bound | F / LB | planning time (ms) | spatial reuse | distributed rounds | conflict-free |",
            "|---|---|---|---|---|---|---|---|"]
    for r in s:
        out.append(f"| {r['N']} | {fmt(r['F'],1)} | {fmt(r['LB'],1)} | {fmt(r['F_over_LB'],3)} | "
                   f"{fmt(r['conflict_ms']+r['greedy_ms'],2)} | {fmt(r['reuse'],2)} | {fmt(r['dist_rounds'],1)} | {r['all_conflict_free']} |")
    out += ["\n![scaling](../results/scaling.png)\n", "## 3. Greedy vs exact optimum\n",
            "| family | N | instances | proven optimal | greedy = optimum | greedy = clique bound | max gap (slots) |",
            "|---|---|---|---|---|---|---|"]
    for r in e:
        out.append(f"| {r['family']} | {r['size']} | {r['instances']} | {r['proven_optimal']} | "
                   f"{fmt(r['greedy_equals_optimum_pct'],0)}% | {fmt(r['greedy_equals_clique_bound_pct'],0)}% | {r['max_gap_slots']} |")
    out += ["\nOn random trees the frame length is set by the gateway (it can receive one packet per slot), "
            "which the clique lower bound captures, so greedy reaches the optimum. On grids greedy loses one slot.\n",
            "![exact](../results/exact.png)\n", "## 4. Realistic interference (SINR + shadowing)\n",
            "| shadowing sigma (dB) | tx failing before repair | frame before | frame after | repair iterations | failures after |",
            "|---|---|---|---|---|---|"]
    for r in si:
        out.append(f"| {r['sigma_db']} | {fmt(r['fail_before_pct'],1)}% | {fmt(r['F_before'],1)} | {fmt(r['F_after'],1)} | "
                   f"{fmt(r['iters'],1)} | {r['max_fail_after']} |")
    out += ["\n![sinr](../results/sinr.png)\n", "## 5. Dynamic join / leave\n",
            f"{dy['events']} events: schedule valid after every event = **{dy['all_valid']}**. "
            f"Nodes re-assigned per event: mean {fmt(dy['mean_reassigned'],1)}, max {dy['max_reassigned']} "
            f"(network size about {fmt(dy['mean_network_size'],0)}, so {fmt(dy['mean_reassigned_pct'],1)}% on average, instead of 100%).\n",
            "![dynamic](../results/dynamic.png)\n", "## 6. Coverage distance from the user\n",
            f"Chain of relays at 0.9 x Rc spacing, {cv['slot_ms']} ms slots.\n",
            "| relays + gateway | coverage (m) | frame, single flow | frame, all nodes report | max rate per node (pkt/s) | worst latency (s) |",
            "|---|---|---|---|---|---|"]
    for r in cv["chain"][::4]:
        out.append(f"| {r['nodes']} | {r['distance_m']:.0f} | {r['F_unit']} | {r['F_conv']} | "
                   f"{fmt(r['max_rate_per_node_pps'],3)} | {fmt(r['worst_latency_ms']/1000,1)} |")
    out += ["\n**Maximum coverage under a service requirement:**\n",
            "| latency budget | rate per node | hops | coverage (m) | frame (slots) |", "|---|---|---|---|---|"]
    for c in cv["constrained"]:
        b_ = c["best"]
        out.append(f"| {c['latency_budget_ms']/1000:.0f} s | {c['rate_per_node_pps']} pkt/s | "
                   + (f"{b_['hops']} | {b_['distance_m']:.0f} | {b_['F_conv']} |" if b_ else "none | - | - |"))
    out += ["\n![coverage](../results/coverage.png)\n"]
    (R / "docs").mkdir(exist_ok=True)
    (R / "docs" / "RESULTS.md").write_text("\n".join(out))
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
